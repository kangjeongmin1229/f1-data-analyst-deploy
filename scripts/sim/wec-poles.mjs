// Real WEC best qualifying/Hyperpole lap per class, track and season (Al Kamel: lap, sectors, weather) for the
// sector correction (raced sessions reproduce exactly). In: .cache/lapsim/wec.json (fetch-wec.mjs).
// Out: worker/lapsim/wec-poles-data.js
import {readFileSync, writeFileSync} from 'node:fs';

const CACHE = process.env.LAPSIM_CACHE || '.cache/lapsim';
const out = {};
for (const r of JSON.parse(readFileSync(process.argv[2] || `${CACHE}/wec.json`, 'utf8'))) {
  const l = r.laps?.[0];
  if (!l || r.weather?.rain || !l.sectors?.every(Number.isFinite)) continue;
  // keep the sectors that add up to the lap (timing resolution)
  if (Math.abs(l.sectors.reduce((a, b) => a + b, 0) - l.lap) > 0.002) continue;
  ((out[r.track] ||= {})[r.year] ||= {})[r.cls] = {lap: +l.lap.toFixed(3), sectors: l.sectors, car: l.car, manufacturer: l.manufacturer, session: l.session, weather: r.weather};
}
writeFileSync('worker/lapsim/wec-poles-data.js', '// Generated by scripts/sim/wec-poles.mjs from Al Kamel timing: best qualifying/Hyperpole lap per WEC class, track and season\nexport const lapsimWecPoles = ' + JSON.stringify(out) + ';\n');
console.log(Object.entries(out).map(([t, y]) => `${t}: ${Object.keys(y).join('/')}`).join('\n'));
