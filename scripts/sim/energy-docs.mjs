// Reads the FIA "Power Unit Information" document of each 2026+ event (published in race week) and
// stores the official recharge limits per session (worker/lapsim/energy-docs-data.js). Until an
// event's document exists, the simulator uses the provisional/estimated value in energy-limits.js.
import {writeFile} from 'node:fs/promises';
import {lapsimTracks} from '../../worker/lapsim/tracks-data.js';
import {eventDocuments, fiaCall} from '../../worker/fia.js';
import {eventFor} from '../../worker/lapsim/names.js';
import {parsePuInfo} from '../../worker/lapsim/pu-info.js';

const now = new Date().getUTCFullYear();
const years = (process.env.LAPSIM_ENERGY_YEARS || [2026, now].filter((y, i, a) => y >= 2026 && a.indexOf(y) === i).join(',')).split(',').map(Number);
const {lapsimEnergyDocs: previous} = await import('../../worker/lapsim/energy-docs-data.js').catch(() => ({lapsimEnergyDocs: {}}));
const out = structuredClone(previous || {});
for (const year of years) for (const id of Object.keys(lapsimTracks)) {
  const name = eventFor(id, year); if (!name) continue;
  try {
    const ev = await eventDocuments(year, name);
    const doc = ev?.records.filter(r => /power unit information/i.test(r.title) && !r.recalled).sort((a, b) => Number(b.document_number || 0) - Number(a.document_number || 0))[0];
    if (!doc) { console.log(`${year} ${id}: no Power Unit Information yet`); continue; }
    const r = JSON.parse((await fiaCall('fia_read_document', {url: doc.url, start_page: 1, page_count: 4, limit: 16000})).content[0].text);
    const v = parsePuInfo(r.pages);
    if (!v) { console.log(`${year} ${id}: recharge table not found in ${doc.title}`); continue; }
    ((out[year] ||= {})[id] = {...v, event: ev.event, document: {title: doc.title, url: doc.url, published: doc.published || null}});
    console.log(`${year} ${id}: qualifying ${v.qualiMJ} MJ, race ${v.raceMJ} MJ (${doc.title})`);
  } catch (e) { console.log(`${year} ${id}: ${e.message}`); }
}
await writeFile('worker/lapsim/energy-docs-data.js', `// Generated by scripts/sim/energy-docs.mjs from FIA "Power Unit Information" event documents.\nexport const lapsimEnergyDocs=${JSON.stringify(out)};\n`);
