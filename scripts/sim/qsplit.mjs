// Qualifying split into Q1/Q2/Q3: each segment's time window (session status in TracingInsights
// session_info.json) and its real best lap (any driver, dry slick laps), per track and season. The
// evolution curve predicts how much quicker the track is at the end of each segment; a segment offset
// (pooled median: different drivers left, fresher tyres in Q3) closes the rest. Tested leave-one-event-out.
// Out: worker/lapsim/qsplit-data.js.
import {readdirSync, readFileSync, existsSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {tiTrack} from './ti-races.mjs';
import {evolutionCoeffs, evolutionDelta} from '../../worker/lapsim/evolution.js';

const ROOT = process.env.LAPSIM_TI || '.cache/lapsim/ti', YEARS = (process.env.LAPSIM_Q_YEARS || '2023,2024,2025,2026').split(',');
const ALIAS = {barcelona: 'catalunya', 'barcelona-catalunya': 'catalunya'}, val = v => v === 'None' || v == null ? null : v;
const read = f => { try { return JSON.parse(readFileSync(f, 'utf8')); } catch { return null; } };
const median = a => { const s = [...a].sort((x, y) => x - y); return (s[(s.length - 1) >> 1] + s[s.length >> 1]) / 2; };
const events = [];
for (const y of YEARS) for (const ev of existsSync(join(ROOT, y)) ? readdirSync(join(ROOT, y)).filter(e => /Grand Prix$/.test(e)) : []) {
  const dir = join(ROOT, y, ev, 'Qualifying'), info = read(join(dir, 'session_info.json'));
  const st = info?.session_status; if (!st?.Time) continue;
  const t0 = info.session_start_time ?? 0, seg = [];
  for (let i = 0; i < st.Status.length; i++) if (st.Status[i] === 'Started') { const e = st.Status.findIndex((s, k) => k > i && s === 'Finished'); if (e > 0) seg.push([(st.Time[i] - t0) / 60, (st.Time[e] - t0) / 60]); }
  if (seg.length !== 3) continue;
  const best = [Infinity, Infinity, Infinity]; let rain = 0, n = 0;
  for (const drv of readdirSync(dir).filter(d => /^[A-Z]{3}$/.test(d))) {
    const L = read(join(dir, drv, 'laptimes.json')); if (!L) continue;
    for (let i = 0; i < L.lap.length; i++) {
      n++; if (L.wR?.[i] === true) rain++;
      const t = val(L.time[i]), s = val(L.lST?.[i]); if (!Number.isFinite(t) || !Number.isFinite(s) || L.del?.[i] === true || !['SOFT', 'MEDIUM', 'HARD'].includes(L.compound?.[i])) continue;
      const m = (s - t0) / 60 + t / 60, k = seg.findIndex(([a, b]) => m >= a && m <= b + 2.5); // a lap started before the flag still counts
      if (k >= 0) best[k] = Math.min(best[k], t);
    }
  }
  if (rain / Math.max(1, n) > 0.03 || !best.every(Number.isFinite)) continue;
  const t = tiTrack(ev, +y), id = ALIAS[t] || t;
  events.push({year: y, id, seg: seg.map(([a, b]) => [+a.toFixed(1), +b.toFixed(1)]), best: best.map(x => +x.toFixed(3))});
}
// evolution prediction of segment best relative to Q3 best: (1 + evo(end k)) / (1 + evo(end Q3))
const pred = e => { const c = evolutionCoeffs('f1', e.id, 'qualifying'), P = {...c, session: 'qualifying', useCurve: !!c.curve}, d = m => evolutionDelta(P, m, Infinity); return e.seg.map(([, b]) => (1 + d(b)) / (1 + d(e.seg[2][1]))); };
for (const e of events) { e.real = e.best.map(x => x / e.best[2]); e.evo = pred(e); }
const off = rs => [0, 1].map(k => median(rs.map(e => e.real[k] - e.evo[k])));
const O = off(events), err = {q1: [], q2: [], q1Evo: [], q2Evo: []};
events.forEach((e, i) => { const o = off(events.filter((_, j) => j !== i)); for (const k of [0, 1]) { err['q' + (k + 1)].push((e.evo[k] + o[k] - e.real[k]) * 100); err['q' + (k + 1) + 'Evo'].push((e.evo[k] - e.real[k]) * 100); } });
const rms = a => +Math.sqrt(a.reduce((s, x) => s + x * x, 0) / a.length).toFixed(3);
const out = {generatedAt: new Date().toISOString(), offsetPct: O.map(x => +(x * 100).toFixed(3)), test: {events: events.length, q1RmsPct: rms(err.q1), q2RmsPct: rms(err.q2), q1EvoOnlyPct: rms(err.q1Evo), q2EvoOnlyPct: rms(err.q2Evo)}, tracks: {}};
for (const e of events) ((out.tracks[e.id] ||= {})[e.year] = {seg: e.seg, best: e.best});
writeFileSync('worker/lapsim/qsplit-data.js', '// Generated by scripts/sim/qsplit.mjs: qualifying Q1/Q2/Q3 windows and real segment bests (TracingInsights)\nexport const lapsimQsplit = ' + JSON.stringify(out) + ';\n');
console.log(events.length, 'dry qualifyings; offsets %', out.offsetPct, 'test', JSON.stringify(out.test));
