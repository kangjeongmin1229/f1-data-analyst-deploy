// Learns how much each kind of circuit change (race director's notes: new kerb, lower kerb,
// resurfacing, bump removal) changes corner speed, from real qualifying speed traces of the same
// track in the season before and the season of the change. Each changed corner is compared with the
// unchanged corners of the same track and lap (removes the new car, the weather and the driver).
// Writes worker/lapsim/change-effects-data.js; the kernel then uses the learned factor instead of
// its assumed one when a type has enough cases.
import {readFile, writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {lapsimTracks} from '../../worker/lapsim/tracks-data.js';
import {lapsimTrackChanges} from '../../worker/lapsim/track-changes-data.js';

const CACHE = process.env.LAPSIM_CACHE || '.cache/lapsim';
const traces = JSON.parse(await readFile(join(CACHE, 'traces.json'), 'utf8'));
const median = a => { const s = [...a].sort((x, y) => x - y); return s.length ? (s[(s.length - 1) >> 1] + s[s.length >> 1]) / 2 : NaN; };
const TYPES = ['kerb_raised', 'kerb_lowered', 'kerb_changed', 'resurfacing', 'bump_removal'];

// lowest speed inside [a, b] (m) of one trace, wrapping at the line
function minSpeed(t, [a, b], L) {
  const s0 = ((a % L) + L) % L, s1 = ((b % L) + L) % L; let v = Infinity;
  for (let i = 0; i < t.s.length; i++) { const s = t.s[i]; if (s0 <= s1 ? s >= s0 && s <= s1 : s >= s0 || s <= s1) v = Math.min(v, t.v[i]); }
  return Number.isFinite(v) ? v : null;
}
// per-corner median (over the top drivers) of the lowest speed, dry laps only
function cornerSpeeds(id, year, corners, L) {
  const ts = traces.filter(t => t.track === id && t.year === year && !t.weather?.rain && (t.position ?? 1) <= 5);
  if (ts.length < 2) return null;
  return Object.fromEntries(corners.map(c => [c.number + (c.letter || ''), median(ts.map(t => minSpeed(t, [c.s - 40, c.s + 40], L)).filter(Number.isFinite))]));
}

const samples = Object.fromEntries(TYPES.map(t => [t, []]));
for (const [id, years] of Object.entries(lapsimTrackChanges)) {
  const td = lapsimTracks[id]; if (!td?.corners?.length) continue;
  const L = td.length;
  for (const [y, e] of Object.entries(years)) {
    const year = Number(y), now = cornerSpeeds(id, year, td.corners, L), before = cornerSpeeds(id, year - 1, td.corners, L);
    if (!now || !before) continue;
    const changes = (e.changes || []).filter(c => TYPES.includes(c.type) && c.range);
    const touched = new Set(changes.flatMap(c => c.corners));
    // also leave out every corner any change of this event names (layout, run-off…): not a clean control
    for (const c of e.changes || []) for (const k of c.corners || []) touched.add(k);
    const control = median(Object.keys(now).filter(k => !touched.has(k) && now[k] > 0 && before[k] > 0).map(k => now[k] / before[k]));
    if (!Number.isFinite(control)) continue;
    for (const c of changes) {
      const r = median(c.corners.filter(k => now[k] > 0 && before[k] > 0).map(k => now[k] / before[k] / control));
      if (Number.isFinite(r) && Math.abs(r - 1) < 0.1) samples[c.type].push({id, year, corners: c.corners, ratio: r, text: c.text});
    }
  }
}

// factor per type: median corner-speed ratio, shrunk toward 1 when there are few cases;
// grip-type changes act on μ (corner speed ∝ √μ)
const learned = {};
for (const [type, list] of Object.entries(samples)) {
  if (!list.length) continue;
  const m = median(list.map(s => s.ratio)), n = list.length, shrink = n / (n + 3);
  const speed = 1 + (m - 1) * shrink, grip = type === 'resurfacing' || type === 'bump_removal';
  learned[type] = {kind: grip ? 'grip' : 'cornerSpeed', factor: Math.round((grip ? speed * speed : speed) * 1e4) / 1e4, n, rawSpeedRatio: Math.round(m * 1e4) / 1e4,
    spread: Math.round(median(list.map(s => Math.abs(s.ratio - m))) * 1e4) / 1e4};
}
await writeFile('worker/lapsim/change-effects-data.js', `// Generated by scripts/sim/change-effects.mjs from real speed traces before/after circuit changes. Do not edit by hand.\nexport const lapsimChangeEffects=${JSON.stringify({generatedAt: new Date().toISOString(), learned})};\n`);
console.log('## Learned circuit-change effects\n\n| Change | Cases | Corner speed | Applied factor | Spread |\n|---|---|---|---|---|');
for (const [t, v] of Object.entries(learned)) console.log(`| ${t} | ${v.n} | ×${v.rawSpeedRatio} | ${v.kind} ×${v.factor} | ±${v.spread} |`);
for (const [t, list] of Object.entries(samples)) for (const s of list) console.log(`- ${t} ${s.id} ${s.year} T${s.corners.join(',')}: ×${s.ratio.toFixed(4)} — ${s.text}`);
