// LMDh regen cap: assumption range (central 2026-11-25 13:48, report only). The shipped cap is 50 kW, assumed: the LMDh TR
// Art. 5.3.10 d) leaves regeneration power to the Equity Model (not public); Bosch's 200 kW is hardware capability. This lists the
// LMDh lap and regen energy at 50 vs 200 kW on 5 tracks with the shipped calibration. node scripts/sim/lmdh-regen-range.mjs [--check]
import {writeFileSync, readFileSync} from 'node:fs';
import {lapsimKernel} from '../../worker/lapsim/kernel.js';
import {lapsimTracks} from '../../worker/lapsim/tracks-data.js';
import {lapsimCalibration as C} from '../../worker/lapsim/calibration-data.js';

const K = lapsimKernel(), TRACKS = ['spa-francorchamps', 'sakhir', 'interlagos', 'imola', 'lusail'], OUT = 'worker/lapsim/lmdh-regen-range-data.js';
const r3 = x => Math.round(x * 1000) / 1000;
export function build() {
  const rows = [];
  for (const y of ['2025', '2026']) for (const id of TRACKS) {
    const car = C.series.wec.lmdh[y].car, t = K.trackFromData(lapsimTracks[id]);
    const a = K.simulateLap(t, car, {}), b = K.simulateLap(t, {...car, ers: {...car.ers, regenMax: 200e3}}, {});
    rows.push({season: y, track: id, lap50s: r3(a.lapTime), lap200s: r3(b.lapTime), deltaS: r3(b.lapTime - a.lapTime), regen50MJ: r3(a.energy.regenJ / 1e6), regen200MJ: r3(b.energy.regenJ / 1e6)});
  }
  const d = Math.max(...rows.map(r => Math.abs(r.deltaS)));
  return {capKW: 50, altKW: 200, label: 'assumed (no published rule; Equity Model not public)',
    sources: ['LMDh Technical Regulations (ACO/IMSA, rev. 2024-10-22) Art. 5.3.10 d): regeneration power subject to the Equity Model',
      'Bosch Motorsport press release (WEC debut 2023): 50 kW in drive mode, up to 200 kW in recuperation (hardware capability)'],
    lapPlusMinusS: d, rows};
}
const text = d => `// generated by scripts/sim/lmdh-regen-range.mjs; do not edit by hand\nexport const lmdhRegenRange = ${JSON.stringify(d)};\n`;
if (import.meta.url === `file://${process.argv[1]}`) {
  const t = text(build());
  if (process.argv.includes('--check')) { if (readFileSync(OUT, 'utf8') !== t) { console.error('stale: rerun scripts/sim/lmdh-regen-range.mjs'); process.exit(1); } }
  else { writeFileSync(OUT, t); console.log('wrote', OUT); }
}
