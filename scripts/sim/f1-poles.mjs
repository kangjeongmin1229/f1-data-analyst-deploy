// Real F1 pole lap per track and season from TracingInsights qualifying laps: fastest valid lap of the LAST
// qualifying segment (Q3 decides pole; a faster Q2 lap is not the pole, e.g. Hungary 2025), not deleted,
// slick, sectors adding up to the lap. Used by the sector correction so raced sessions reproduce exactly,
// whichever driver's telemetry the speed-trace fit used. In: TracingInsights season repos (sparse clone,
// LAPSIM_TI_DIR). Out: worker/lapsim/f1-poles-data.js
import {existsSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {tiTrack} from './ti-races.mjs';

const ROOT = process.env.LAPSIM_TI_DIR || '.cache/ti', YEARS = (process.env.LAPSIM_POLE_YEARS || '2025,2026').split(',');
const num = v => v === 'None' || v == null || !Number.isFinite(+v) ? null : +v;
const out = {};
for (const y of YEARS) {
  if (!existsSync(join(ROOT, y))) continue;
  for (const ev of readdirSync(join(ROOT, y)).filter(e => /Grand Prix$/.test(e))) {
    const dir = join(ROOT, y, ev, 'Qualifying'); if (!existsSync(dir)) continue;
    let best = null; const all = [];
    for (const drv of readdirSync(dir)) {
      const f = join(dir, drv, 'laptimes.json'); if (!existsSync(f)) continue;
      const d = JSON.parse(readFileSync(f, 'utf8'));
      d.time.forEach((t, i) => {
        const lap = num(t), s = [num(d.s1[i]), num(d.s2[i]), num(d.s3[i])];
        if (lap == null || d.del?.[i] || !['SOFT', 'MEDIUM', 'HARD'].includes(d.compound?.[i]) || s.some(x => x == null)) return;
        if (Math.abs(s[0] + s[1] + s[2] - lap) > 0.002) return;
        all.push({driver: drv, number: d.dNum?.[i] ?? null, lap, sectors: s, seg: d.qs?.[i] || ''});
      });
    }
    const last = all.map(l => l.seg).filter(Boolean).sort().at(-1) ?? '';
    for (const l of all.filter(l => l.seg === last)) if (!best || l.lap < best.lap) best = l;
    if (best) ((out[tiTrack(ev, +y)] ||= {})[y] = best);
  }
}
writeFileSync('worker/lapsim/f1-poles-data.js', '// Generated by scripts/sim/f1-poles.mjs from TracingInsights qualifying laps: real pole lap and sectors per track and season\nexport const lapsimF1Poles = ' + JSON.stringify(out) + ';\n');
for (const [t, ys] of Object.entries(out)) console.log(t.padEnd(20), Object.entries(ys).map(([y, p]) => `${y} ${p.driver} ${p.lap}`).join('  '));
