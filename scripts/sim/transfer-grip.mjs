// Writes worker/lapsim/transfer-grip-data.js: per-track grip factors from an F1 calibration run without
// per-track drag (LAPSIM_TRACK_DRAG=off), used for the WEC fit. node scripts/sim/transfer-grip.mjs <cal.js> [label]
import {writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
const [file, label = 'F1 fit without per-track drag'] = process.argv.slice(2);
const {lapsimCalibration: c} = await import(pathToFileURL(file).href);
const grip = {};
for (const y of Object.keys(c.seasons).sort()) for (const [id, t] of Object.entries(c.seasons[y].tracks || {})) if (t.grip != null) grip[id] = +t.grip.toFixed(4);
const out = {source: label, generated: new Date().toISOString().slice(0, 10), grip};
writeFileSync('worker/lapsim/transfer-grip-data.js', `// Generated by scripts/sim/transfer-grip.mjs — do not edit.\nexport const lapsimTransferGrip = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(grip).length, 'tracks');
