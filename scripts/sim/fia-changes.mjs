// Reads the latest Race Director's Event/Competition Notes for each simulator track and stores
// the parsed "Changes to the circuit" list (worker/lapsim/track-changes-data.js).
import {writeFile} from 'node:fs/promises';
import {lapsimTracks} from '../../worker/lapsim/tracks-data.js';
import {eventDocuments, fiaCall} from '../../worker/fia.js';
import {parseTrackChanges} from '../../worker/lapsim/track-changes.js';
import {eventFor} from '../../worker/lapsim/names.js';

const NOTES = /event notes|competition notes/i;

async function readAll(url) {
  const pages = [];
  for (let start = 1; start < 60;) {
    const r = JSON.parse((await fiaCall('fia_read_document', {url, start_page: start, page_count: 5, limit: 16000})).content[0].text);
    if (!r.pages?.length) break;
    pages.push(...r.pages.map(p => p.text));
    if (!r.next_page) break;
    start = r.next_page;
  }
  return pages.join('\n');
}

const years = (process.env.LAPSIM_CHANGE_YEARS || String(new Date().getUTCFullYear())).split(',').map(Number);
// start from the stored list so a track the FIA site does not answer for keeps its last good entry
const {lapsimTrackChanges: previous} = await import('../../worker/lapsim/track-changes-data.js').catch(() => ({lapsimTrackChanges: {}}));
const out = structuredClone(previous || {});
for (const [id, track] of Object.entries(lapsimTracks)) {
  for (const year of years) {
    const name = eventFor(id, year);
    if (!name) { console.log(`${id} ${year}: no FIA event for this track`); continue; }
    try {
      const ev = await eventDocuments(year, name);
      if (!ev) { console.log(`${id} ${year}: event not published`); continue; }
      const docs = ev.records.filter(r => NOTES.test(r.title) && !r.recalled && !/SC2|SC1|times/i.test(r.title));
      // highest version of the notes (V3 over V2 over the first issue)
      docs.sort((a, b) => (Number(b.title.match(/V(\d+)\b/)?.[1] || 1) - Number(a.title.match(/V(\d+)\b/)?.[1] || 1)) || (Number(b.document_number || 0) - Number(a.document_number || 0)));
      const doc = docs[0];
      if (!doc) { console.log(`${id} ${year}: no notes yet`); continue; }
      const text = await readAll(doc.url);
      const parsed = parseTrackChanges(text, {title: doc.title, url: doc.url, published: doc.published || null, event: ev.event, year});
      out[id] = {...(out[id] || {}), [year]: {event: ev.event, document: {title: doc.title, url: doc.url, published: doc.published || null},
        sectionFound: parsed.sectionFound, changes: parsed.changes.map(({source, ...c}) => c)}};
      console.log(`${id} ${year}: ${parsed.changes.length} changes (${parsed.changes.filter(c => c.affectsLap).length} affect the lap)`);
    } catch (e) { console.log(`${id} ${year}: ${e.message}`); }
  }
}
await writeFile('worker/lapsim/track-changes-data.js', `// Generated by scripts/sim/fia-changes.mjs from FIA Race Director's notes ("Changes to the circuit").\nexport const lapsimTrackChanges=${JSON.stringify(out)};\n`);
