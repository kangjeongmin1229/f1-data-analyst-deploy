// Year-on-year pole-time change on unchanged circuit layouts, grouped by the year within a
// regulation cycle. Source: f1db (CC BY 4.0, https://github.com/f1db/f1db).
// Usage: node scripts/sim/pole-trend.mjs <path to f1db checkout>  -> worker/lapsim/pole-trend.js
import {readdir, readFile, writeFile} from 'node:fs/promises';
import {join} from 'node:path';

const root = join(process.argv[2], 'src/data/seasons');
const field = (text, name) => (text.match(new RegExp(`^${name}:\\s*"?([^"\\n]*)"?`, 'm')) || [])[1];
const secs = t => { if (!t) return null; const m = t.match(/^(?:(\d+):)?(\d+\.\d+)$/); return m ? (m[1] ? +m[1] * 60 : 0) + +m[2] : null; };

const poles = {}; // year -> layoutId -> seconds
for (const year of (await readdir(root)).map(Number).filter(y => y >= 2012).sort()) {
  poles[year] = {};
  for (const race of await readdir(join(root, String(year), 'races'))) {
    let raceYml, qual;
    try { raceYml = await readFile(join(root, String(year), 'races', race, 'race.yml'), 'utf8'); qual = await readFile(join(root, String(year), 'races', race, 'qualifying-results.yml'), 'utf8'); }
    catch { continue; }
    const layout = field(raceYml, 'circuitLayoutId');
    const first = qual.split(/^- /m).find(b => /^position:\s*1\s*$/m.test(b));
    if (!layout || !first) continue;
    const t = [secs(field(first, '  q3')) ?? secs(field(first, 'q3')), secs(field(first, '  q2')) ?? secs(field(first, 'q2')), secs(field(first, '  q1')) ?? secs(field(first, 'q1')), secs(field(first, '  time')) ?? secs(field(first, 'time'))].filter(Number.isFinite);
    if (t.length) poles[year][layout] = Math.min(...t);
  }
}
// Regulation cycles (first year of each): 2009 aero rules, 2014 power units, 2017 wider cars, 2022 ground effect, 2026 new cars and PUs
const cycleStart = y => (y >= 2026 ? 2026 : y >= 2022 ? 2022 : y >= 2017 ? 2017 : y >= 2014 ? 2014 : 2009);
const median = a => { const s = [...a].sort((x, y) => x - y); const m = s.length >> 1; return s.length ? (s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2) : null; };
const q = (a, p) => { const s = [...a].sort((x, y) => x - y); return s.length ? s[Math.min(s.length - 1, Math.floor(p * s.length))] : null; };
const transitions = [];
for (const y of Object.keys(poles).map(Number)) {
  const next = poles[y + 1]; if (!next || cycleStart(y) !== cycleStart(y + 1)) continue;
  const changes = Object.keys(poles[y]).filter(l => next[l]).map(l => (next[l] / poles[y][l] - 1) * 100);
  if (changes.length < 6) continue;
  transitions.push({from: y, to: y + 1, cycleYear: y - cycleStart(y) + 1, circuits: changes.length,
    medianPct: +median(changes).toFixed(2), p25: +q(changes, 0.25).toFixed(2), p75: +q(changes, 0.75).toFixed(2)});
}
const byStep = {};
for (const t of transitions) (byStep[t.cycleYear] ||= []).push(t.medianPct);
const steps = Object.fromEntries(Object.entries(byStep).map(([k, v]) => [k, {meanOfMedians: +(v.reduce((a, b) => a + b, 0) / v.length).toFixed(2), min: Math.min(...v), max: Math.max(...v), cycles: v.length}]));
await writeFile('worker/lapsim/pole-trend.js', `// Generated by scripts/sim/pole-trend.mjs from f1db (CC BY 4.0). Pole-time change in % between\n// consecutive years on unchanged layouts; cycleYear 1 = first year of a regulation cycle.\nexport const poleTrend=${JSON.stringify({source: 'f1db (CC BY 4.0)', transitions, steps})};\n`);
console.table(transitions); console.log(steps);
