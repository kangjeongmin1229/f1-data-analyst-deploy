// Real best qualifying lap per series, class, track and season for every series we plan to simulate, from the
// Timing71 summaries (complete replays: chequered flag; dry). Stored for all tracks; sessions on tracks with
// geometry reproduce now (provisional car + lap correction), the rest once their geometry is built.
//   node scripts/sim/series-poles.mjs [summaryDir]
//   → scripts/sim/data/series-poles.json (all) and worker/lapsim/series-poles-data.js (tracks with geometry)
import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {mapSessions} from './t71-tracks.mjs';
import {lapsimTracks} from '../../worker/lapsim/tracks-data.js';

const dir = process.argv[2] || 'scripts/sim/data/t71';
// class of a car for the series we simulate (null = not simulated, e.g. LMP2/LMP3, GT4, TCR)
const CLASS = {
  imsa: c => /^GTP$/i.test(c) ? 'gtp' : /^GTDPRO$/i.test(c) ? 'gtdpro' : /^GTD$/i.test(c) ? 'gtd' : null,
  elms: (c, y) => /LMGT3/i.test(c) || (/GTE/i.test(c) && y >= 2024) ? 'lmgt3' : null,
  alms: c => /^GT$/i.test(c) ? 'gt3' : null,
  gtwc: c => /gt4|tcr/i.test(c) ? null : 'gt3', dtm: () => 'gt3', igtc: c => /gt4|tcr/i.test(c) ? null : 'gt3',
  nur: c => /SP9|SP-X|^SP 9/i.test(c) ? 'gt3' : null, macau: () => 'gt3', fe: () => 'fe',
};
const out = {};
for (const key of Object.keys(CLASS)) {
  if (!existsSync(`${dir}/${key}.json`)) continue;
  for (const s of mapSessions(JSON.parse(readFileSync(`${dir}/${key}.json`, 'utf8')).sessions.map(x => ({...x, key})))) {
    if (s.kind !== 'Q' || !s.track || s.weather?.wet > 0) continue;
    if (key === 'macau' && !/gt/i.test(s.description)) continue; // Macau: GT World Cup sessions only
    const complete = s.endFlag === 'chequered'; if (!complete && key !== 'nur') continue; // NLS feeds carry no flag state
    const y = new Date(s.start * 1e3).getUTCFullYear(), byCls = {};
    for (const [num, c] of Object.entries(s.cars)) {
      const k = CLASS[key](c.cls || '', y); if (!k || !c.best) continue;
      if (!byCls[k] || c.best < byCls[k].lap) byCls[k] = {lap: c.best, sectors: c.bestS, car: num, make: c.make, team: c.team};
    }
    for (const [k, r] of Object.entries(byCls)) {
      const slot = ((out[key] ||= {})[s.track] ||= {})[y] ||= {};
      if (!slot[k] || r.lap < slot[k].lap) slot[k] = {...r, session: s.description, complete,
        weather: s.weather ? {airTempC: s.weather.air, trackTempC: s.weather.track, humidityPct: s.weather.hum, pressureHpa: s.weather.press, windSpeed: s.weather.wind} : null};
    }
  }
}
writeFileSync('scripts/sim/data/series-poles.json', JSON.stringify({source: 'Timing71 archive (complete replays); calibration use only', series: out}));
const geo = {};
for (const [ser, tr] of Object.entries(out)) for (const [t, ys] of Object.entries(tr)) if (lapsimTracks[t] && ser !== 'fe') (geo[ser] ||= {})[t] = ys;
writeFileSync('worker/lapsim/series-poles-data.js', '// Generated by scripts/sim/series-poles.mjs (Timing71): real best qualifying lap per series, class, track and season on simulator tracks\nexport const lapsimSeriesPoles = ' + JSON.stringify(geo) + ';\n');
for (const [ser, tr] of Object.entries(out)) {
  const all = Object.entries(tr), g = all.filter(([t]) => lapsimTracks[t] && ser !== 'fe');
  console.log(ser.padEnd(6), `tracks ${all.length}, with geometry ${g.length}:`, g.map(([t, ys]) => `${t}(${Object.keys(ys).join(',')})`).join(' ') || '-');
}
